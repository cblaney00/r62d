// Meta defaults (he asked 2026-11-15: every operator's default loadout = what the pros prefer, so players see what the
// pros are working with and get pointed at the current meta). From the pros' practice records (training.guns 'op|gun'
// and training.att 'gun|slot|choice', each [rounds, wins, kills, deaths]): per operator the main gun and sidearm the pros
// play most with them, and per gun the barrel, grip, sight and ammo they run most. shared/operators.js
// defaultLoadout/defaultAtt read META (shared/meta.js). The server refreshes META from practice at start-up and after
// every practice session (refreshMeta) and hands it to browsers at /api/meta, so the defaults follow the meta by themselves.
// `node server/metaloadouts.js` also writes the current one into shared/meta.js (the fallback a fresh copy starts with).
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { training } from './training.js';
import { LOADOUTS, WEAPONS, attachFor, OPERATORS } from '../shared/operators.js';
import { META } from '../shared/meta.js';

const MIN_OP = 10, MIN_ATT = 15;
const most = list => list.sort((a, b) => b[1][0] - a[1][0] || (b[1][1] / b[1][0]) - (a[1][1] / a[1][0]))[0];
export function computeMeta() {
  const ops = {}, guns = {};
  for (const op of Object.keys(LOADOUTS)) {
    if (!OPERATORS[op]) continue;
    const L = LOADOUTS[op], rec = w => (training.guns || {})[op + '|' + w];
    const pick = list => { const c = list.filter(w => WEAPONS[w] && rec(w) && rec(w)[0] >= MIN_OP).map(w => [w, rec(w)]); const b = c.length && most(c); return b ? b[0] : null; };
    const p = pick(L.primaries), s = pick(L.secondaries);
    if (p || s) ops[op] = { ...(p ? { p } : {}), ...(s ? { s } : {}) };
  }
  for (const w of Object.keys(WEAPONS)) {
    const ok = attachFor(w), set = {};
    for (const slot of ['barrel', 'grip', 'sight', 'ammo']) {
      const c = (ok[slot] || []).map(ch => [ch, (training.att || {})[w + '|' + slot + '|' + ch]]).filter(([, r]) => r && r[0] >= MIN_ATT);
      const b = c.length && most(c); if (b) set[slot] = b[0];
    }
    if (Object.keys(set).length) guns[w] = set;
  }
  return { ops, guns };
}
// put the newest meta into the shared META object in place (everything that reads it sees the change)
export function refreshMeta() {
  const m = computeMeta(); if (!Object.keys(m.ops).length) return META; // no practice yet: keep the shipped one
  for (const k of ['ops', 'guns']) { for (const x of Object.keys(META[k])) delete META[k][x]; Object.assign(META[k], m[k]); }
  META.at = training.at || Date.now(); return META;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const m = computeMeta();
  const out = `// GENERATED by server/metaloadouts.js from the pros' practice (${training.rounds} rounds in all, version ${training.version}, ${new Date().toISOString().slice(0, 10)}).
// Default loadouts = what the pros prefer (he asked). The server refreshes this from practice by itself; this copy is the
// starting point for a fresh install. Re-run after practice to update it.
export const META = ${JSON.stringify(m).replace(/\},"/g, '},\n  "')};\n`;
  fs.writeFileSync(new URL('../shared/meta.js', import.meta.url), out);
  console.log(`meta defaults: ${Object.keys(m.ops).length} operators, ${Object.keys(m.guns).length} guns`);
}
